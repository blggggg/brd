CREATE TABLE IF NOT EXISTS upload_job (
 id VARCHAR(36) NOT NULL PRIMARY KEY,
 actor_id BIGINT NOT NULL,
 request_key VARCHAR(80) NOT NULL,
 request_hash VARCHAR(64) NOT NULL,
 document_id BIGINT NULL,
 base_version_id BIGINT NULL,
 title VARCHAR(160) NULL,
 project_name VARCHAR(120) NULL,
 delivery_batch VARCHAR(80) NULL,
 change_note VARCHAR(500) NOT NULL,
 original_filename VARCHAR(255) NOT NULL,
 extension VARCHAR(8) NOT NULL,
 sha256 VARCHAR(64) NOT NULL,
 size_bytes BIGINT NOT NULL,
 temp_key VARCHAR(80) NOT NULL,
 state VARCHAR(20) NOT NULL,
 error_code VARCHAR(80) NULL,
 result_version_id BIGINT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE KEY uq_upload_actor_request (actor_id, request_key),
 CONSTRAINT fk_upload_actor FOREIGN KEY (actor_id) REFERENCES app_user(id)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS operation_log (
 id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
 actor_id BIGINT NOT NULL,
 action VARCHAR(50) NOT NULL,
 document_id BIGINT NULL,
 version_id BIGINT NULL,
 from_version_id BIGINT NULL,
 reason VARCHAR(500) NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 INDEX idx_operation_document (document_id, id)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS SPRING_SESSION (
 PRIMARY_ID CHAR(36) NOT NULL,
 SESSION_ID CHAR(36) NOT NULL,
 CREATION_TIME BIGINT NOT NULL,
 LAST_ACCESS_TIME BIGINT NOT NULL,
 MAX_INACTIVE_INTERVAL INT NOT NULL,
 EXPIRY_TIME BIGINT NOT NULL,
 PRINCIPAL_NAME VARCHAR(100) NULL,
 PRIMARY KEY (PRIMARY_ID),
 UNIQUE KEY SPRING_SESSION_IX1 (SESSION_ID),
 KEY SPRING_SESSION_IX2 (EXPIRY_TIME),
 KEY SPRING_SESSION_IX3 (PRINCIPAL_NAME)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS SPRING_SESSION_ATTRIBUTES (
 SESSION_PRIMARY_ID CHAR(36) NOT NULL,
 ATTRIBUTE_NAME VARCHAR(200) NOT NULL,
 ATTRIBUTE_BYTES BLOB NOT NULL,
 PRIMARY KEY (SESSION_PRIMARY_ID, ATTRIBUTE_NAME),
 CONSTRAINT SPRING_SESSION_ATTRIBUTES_FK FOREIGN KEY (SESSION_PRIMARY_ID)
   REFERENCES SPRING_SESSION(PRIMARY_ID) ON DELETE CASCADE
) ENGINE=InnoDB;
