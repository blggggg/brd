CREATE TABLE IF NOT EXISTS misc_setup (
 COMPANY_ID BIGINT NOT NULL DEFAULT 0,
 SAMPLE_TYPE_ID BIGINT NOT NULL DEFAULT 0,
 LOCATION_ID BIGINT NOT NULL DEFAULT 0,
 PROPERTY_ID BIGINT NOT NULL,
 PROPERTY_DESC VARCHAR(500) NOT NULL,
 DATE_CREATED DATETIME NULL DEFAULT CURRENT_TIMESTAMP,
 ENABLE_DATE DATETIME NULL DEFAULT CURRENT_TIMESTAMP,
 PRIMARY KEY (COMPANY_ID, SAMPLE_TYPE_ID, LOCATION_ID, PROPERTY_ID)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS task (
 id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
 company_id BIGINT NOT NULL,
 report_format_id INT NOT NULL DEFAULT 0,
 class_name VARCHAR(255) NOT NULL,
 order_no INT NOT NULL DEFAULT 0,
 enabled BOOLEAN NOT NULL DEFAULT TRUE,
 other_fields JSON NOT NULL,
 remark VARCHAR(500) NOT NULL DEFAULT '',
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 INDEX idx_task_company_format_order (company_id, report_format_id, order_no, id),
 CONSTRAINT fk_task_company FOREIGN KEY (company_id) REFERENCES company(id)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS app_user (
 id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
 username VARCHAR(40) NOT NULL UNIQUE,
 display_name VARCHAR(80) NOT NULL,
 password_hash VARCHAR(255) NOT NULL,
 role VARCHAR(20) NOT NULL,
 enabled BOOLEAN NOT NULL DEFAULT TRUE,
 must_change BOOLEAN NOT NULL DEFAULT TRUE,
 auth_version BIGINT NOT NULL DEFAULT 0,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS brd_document (
 id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
 title VARCHAR(160) NOT NULL,
 project_name VARCHAR(120) NOT NULL,
 delivery_batch VARCHAR(80) NOT NULL,
 owner_id BIGINT NOT NULL,
 current_version_id BIGINT NULL,
 latest_version_id BIGINT NULL,
 next_sequence INT NOT NULL DEFAULT 1,
 revision BIGINT NOT NULL DEFAULT 0,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT fk_document_owner FOREIGN KEY (owner_id) REFERENCES app_user(id),
 INDEX idx_document_updated (updated_at)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS brd_version (
 id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
 document_id BIGINT NOT NULL,
 sequence_no INT NOT NULL,
 base_version_id BIGINT NULL,
 object_key VARCHAR(80) NOT NULL UNIQUE,
 original_filename VARCHAR(255) NOT NULL,
 extension VARCHAR(8) NOT NULL,
 sha256 VARCHAR(64) NOT NULL,
 size_bytes BIGINT NOT NULL,
 change_note VARCHAR(500) NOT NULL,
 uploaded_by BIGINT NOT NULL,
 uploaded_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE KEY uq_version_sequence (document_id, sequence_no),
 UNIQUE KEY uq_version_sha256 (document_id, sha256),
 CONSTRAINT fk_version_document FOREIGN KEY (document_id) REFERENCES brd_document(id),
 CONSTRAINT fk_version_base FOREIGN KEY (base_version_id) REFERENCES brd_version(id),
 CONSTRAINT fk_version_uploader FOREIGN KEY (uploaded_by) REFERENCES app_user(id)
) ENGINE=InnoDB;

