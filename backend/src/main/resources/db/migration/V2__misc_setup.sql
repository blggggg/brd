CREATE TABLE IF NOT EXISTS misc_setup (
 COMPANY_ID BIGINT NOT NULL DEFAULT 0,
 SAMPLE_TYPE_ID BIGINT NOT NULL DEFAULT 0,
 LOCATION_ID BIGINT NOT NULL DEFAULT 0,
 PROPERTY_ID BIGINT NOT NULL,
 PROPERTY_DESC VARCHAR(100) NOT NULL,
 DATE_CREATED TIMESTAMP NULL DEFAULT CURRENT_TIMESTAMP,
 ENABLE_DATE TIMESTAMP NULL DEFAULT CURRENT_TIMESTAMP,
 PRIMARY KEY (COMPANY_ID,SAMPLE_TYPE_ID,LOCATION_ID,PROPERTY_ID)
);
